# make_recipes.py: one small playable record per recipe of recipes.txt, for
# the app's Instrument tab. Host only, run by `make recipes`:
#   python3 -I make_recipes.py MUSIC_DIR HARNESS ENGINE OUT_DIR [CHOSEN_RECIPES]
# Export mode adds --export before those arguments, then PATCH_LINES NAME.
# MUSIC_DIR contains compose.py, which locates the shared recipe data.
# Each record is written by hand as an authoring timeline with a recipe
# statement, expanded by compose.py's own expand_timeline (--expand), played
# by the shared harness, and given the hash it printed. A recipe that fails
# is listed with its diagnostic in manifest.json; no failed record remains.
import json
import os
import re
import subprocess
import sys

def load_composer(music):
    sys.path.insert(0, music)
    import compose
    return compose

TEMPLATE = """# recipe {name}: {note}
# generated by make_recipes.py one voice, one note
timeline draft2
engine {engine}
fs 48000
length_ns 2500000000
space off
streams main
recipe {patch} {name}
voice 0 {patch}
0 main 0 on 261626 26000
1500000000 main 0 off
"""

def make_records(compose, harness, engine, out, chosen=None):
    """Use the same composer expansion for build-time and chosen-file import.
    The manifest retains failures; no failed render gets a hash or a record.
    """
    os.makedirs(out, exist_ok=True)
    src = os.path.join(out, 'src')
    os.makedirs(src, exist_ok=True)
    for name in os.listdir(out):
        if name.endswith('.tl'):
            os.remove(os.path.join(out, name))
    entries = []
    try:
        recipes = compose.load_recipes(chosen) if chosen else compose.RECIPES
    except (SystemExit, ValueError, OSError) as e:
        entries.append(dict(name=os.path.basename(chosen), error=str(e)))
        recipes = {}
    compose.RECIPES = recipes
    for name, (car, mod, note, *_) in recipes.items():
        patch = name if re.fullmatch(r'[A-Za-z0-9_.-]{1,31}', name) else 'recipe'
        authored = os.path.join(src, name + '.in')
        record = os.path.join(out, name + '.tl')
        try:
            with open(authored, 'w') as f:
                f.write(TEMPLATE.format(name=name, note=' '.join(str(note).split()), engine=engine, patch=patch))
            compose.expand_timeline(authored, record)
            run = subprocess.run([harness, '--play', record], capture_output=True, text=True)
            m = re.search(r'^PLAY hash=([0-9a-f]{16})\b.*\bblock_indep=yes\b', run.stdout, re.M)
            if run.returncode or not m:
                raise ValueError((run.stderr or run.stdout).strip() or 'harness refused the expanded recipe')
            with open(record, 'a') as f:
                f.write('hash %s\n' % m.group(1))
            entries.append(dict(name=name, file=name + '.tl'))
        except (SystemExit, ValueError, OSError) as e:
            try:
                os.remove(record)
            except OSError:
                pass
            entries.append(dict(name=name, error=str(e)))
            print('recipes: skip %s: %s' % (name, e))
    with open(os.path.join(out, 'manifest.json'), 'w') as f:
        json.dump(entries, f, ensure_ascii=False, indent=2)
        f.write('\n')
    made = sum('file' in e for e in entries)
    print('recipes: %d records in %s, %d skipped' % (made, out, len(entries) - made))
    return entries



def matched_recipe_banks(compose, harness, engine, rows):
    """Recognize only complete native-equivalent banks of offered recipe forms.
    Names nominate candidates; native-expanded bank/data/hash bytes decide.
    Unknown, custom or unused assets keep the existing partial-export path.
    """
    import tempfile
    forms = getattr(compose, 'RECIPE_WT_FORMS', getattr(compose, 'HARMONIC_FORMS', ()))
    tokens = [line.split() for line in rows]
    candidates = sorted({t[3] for t in tokens if t[0] == 'wtuse' and t[3] in forms})
    if not candidates:
        return set()
    harmonics = getattr(compose, 'recipe_harmonics', compose.harmonic_form)
    with tempfile.TemporaryDirectory(prefix='fmspike-export-banks-') as tmp:
        source, merged = (os.path.join(tmp, name) for name in ('source.tl', 'merged.tl'))
        header = ['timeline draft2', 'engine ' + engine, 'fs 48000',
                  'length_ns 1000000', 'space off', 'streams main']
        header += compose.patch_headers('probe', compose.op(), compose.op())
        for bank in candidates:
            header += compose.wtbank_rows(bank, (1, 2048, harmonics(bank)))
        header += ['voice 0 probe']
        with open(source, 'w', encoding='utf-8') as f:
            f.write('\n'.join(header) + '\n')
        run = subprocess.run([harness, '--play', source, '--merged', merged], capture_output=True, text=True)
        if run.returncode or not re.search(r'^PLAY .*\bblock_indep=yes\b', run.stdout, re.M):
            raise ValueError((run.stderr or run.stdout).strip() or 'native form comparison refused')
        with open(merged, encoding='utf-8') as f:
            canonical = [line for line in f.read().splitlines() if line.strip()]
    asset_rows = ('wtbank', 'wtdata', 'wthash')
    matched = set()
    for bank in candidates:
        original = [line for line in rows if line.split()[0] in asset_rows and line.split()[1] == bank]
        expected = [line for line in canonical if line.split()[0] in asset_rows and line.split()[1] == bank]
        if original == expected:
            matched.add(bank)
    return matched


def export_recipe(compose, harness, engine, out, source, name):
    """Invert accepted integer operator tokens; composer owns all validation.
    Every row not carried exactly is retained verbatim as a pending comment.
    The app compares the native re-import with these comments before publish.
    """
    from decimal import Decimal, localcontext
    rows = [line for line in open(source).read().splitlines() if line.strip()]
    tokens = [line.split() for line in rows]
    routing = None
    for t in tokens:
        if t[0] == 'route':
            edges = []
            for edge in t[4:]:
                ends, weight, *kind = edge.split(':')
                a, b = ends.split('>')
                edges.append((int(a), int(b), int(weight), *(kind or [])))
            routing = dict(ops=int(t[2]), carriers=int(t[3]), edges=edges)
    fields = ('ratio', 'level', 'index', 'fb', 'vel', 'a', 'd', 's', 'r',
              'ks_break', 'ks_slope', 'wave', 'rs', 'fixed', 'phase', 'free')
    scales = (65536, 10, 1024, 1024, 1, 1, 1, 10, 1, 1000, 10, 1, 1, 1000, 65536, 1)
    defaults = compose.op() + [0, 0, 0, 0]
    carried = {'route', 'filter', 'shape', 'amp', 'lfo', 'peg', 'fenv', 'mod', 'eg', 'ks',
               'kstype', 'fbtype', 'egloop', 'noise', 'pd', 'vector', 'formant'}
    matched_banks = matched_recipe_banks(compose, harness, engine, rows)
    # Only bindings carried into this recipe can support a WT-position row.
    # Collect first: native modulation rows may precede their wtuse statement.
    exported_wt_ops = {int(t[2]) for t in tokens
                       if t[0] == 'wtuse' and t[3] in matched_banks}
    body, pending = ['recipe ' + name], []
    for line, t in zip(rows, tokens):
        if t[0] == 'patch':
            i = int(t[2]); raw = list(map(int, t[3:]))
            raw += [0] * (len(fields) - len(raw))
            words, lost = [], False
            for k, (key, unit) in enumerate(zip(fields, scales)):
                side = 'c' if i == 0 else 'm' if i == 1 else 'o%d' % i
                if compose.ignored(side, key, routing):
                    lost |= raw[k] != defaults[k]
                    continue
                with localcontext() as ctx:
                    ctx.prec = compose.NUMERIC_PREC
                    value = Decimal(raw[k]) * (360 if key == 'phase' else 1) / unit
                    text = format(value, 'f')
                words.append(key + '=' + text)
            body.append(('carrier' if i == 0 else 'modulator' if i == 1 else 'op %d' % i) + ' ' + ' '.join(words))
            if lost: pending.append(line)
        elif t[0] in ('wtbank', 'wtdata', 'wthash') and t[1] in matched_banks:
            continue
        elif t[0] == 'wtuse' and t[3] in matched_banks:
            body.append(' '.join([t[0], *t[2:]]))
        elif t[0] in carried:
            if t[0] == 'mod':
                # A newer engine target may have no recipe spelling yet.
                # Ask the existing writer rather than copying its enum list.
                try:
                    target = compose.mod_values((int(t[2]), t[3], t[4], *map(int, t[5:])))[2]
                except ValueError:
                    pending.append(line)
                    continue
                # Scalar syntax support does not supply an omitted custom bank.
                if target.startswith('wt_pos') and int(target[len('wt_pos'):]) not in exported_wt_ops:
                    pending.append(line)
                    continue
            body.append(' '.join([t[0], *t[2:]]))
        else:
            pending.append(line)
    body.append('note exported patch; pending comments preserve unrepresented source statements')
    body += ['# pending: ' + line for line in pending]
    os.makedirs(out, exist_ok=True)
    chosen = os.path.join(out, 'export-recipes.txt')
    with open(chosen, 'w') as f:
        f.write('\n'.join(body) + '\n')
    # load_recipes/list_recipes are precisely the --recipes implementation.
    compose.RECIPES = compose.load_recipes(chosen)
    import contextlib
    with open(os.path.join(out, 'listed.txt'), 'w') as f, contextlib.redirect_stdout(f):
        compose.list_recipes()
    entries = make_records(compose, harness, engine, os.path.join(out, 'preview'))
    if len(entries) != 1 or entries[0].get('error'):
        raise ValueError('Export preview refused: ' + str(entries))
    return chosen


if __name__ == '__main__':
    try:
        if sys.argv[1:2] == ['--export']:
            music, harness, engine, out, source, name = sys.argv[2:8]
            export_recipe(load_composer(music), harness, engine, out, source, name)
        else:
            music, harness, engine, out = sys.argv[1:5]
            chosen = sys.argv[5] if len(sys.argv) == 6 else None
            make_records(load_composer(music), harness, engine, out, chosen)
    except (ValueError, OSError) as error:
        sys.exit('Recipe file refused: ' + str(error))
